#!/usr/bin/env python3
"""Build a SHARC boot image from our kernel and a program.

usage: mkboot.py kernel.asm program.asm [more.asm ...] [-o image.bin] [-c image.h NAME] [-e ENTRY]

Several program files are assembled as one source, in the order given. The
image is a sequence of little-endian 32-bit words:

    384 words          the kernel: instruction slots 0x8c000..0x8c0ff
    address, count, count words     one record per program section
    entry, 0           start the program (ENTRY label, default START)

Each word goes out over SPI least significant bit first (src/sharc_boot.c).
48-bit code is carried as 32-bit words, three for every two instructions, at
the 32-bit address of its memory: 0x80000 + (A - 0x80000) * 3 / 2.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sasm

KBASE, KLEN = 0x8C000, 256


def pack48(ins):
    """Pairs of 48-bit instructions -> 32-bit words (little-endian byte run)."""
    assert len(ins) % 2 == 0
    raw = b"".join(i.to_bytes(6, "little") for i in ins)
    return list(struct.unpack("<%dI" % (len(raw) // 4), raw))


def nw32(a48):
    return 0x80000 + (a48 - 0x80000) * 3 // 2


MAXREC = 0x8000                 # words in one record: well inside a 16-bit DMA count


def read_all(paths):
    return "".join(open(p).read().rstrip("\n") + "\n" for p in paths)


def build(kernel_src, prog_srcs, entry="START", data=()):
    """Boot image words. `data`: further (address, 32-bit words) to load."""
    prog_src = " + ".join(prog_srcs)
    ksec, _ = sasm.assemble(open(kernel_src).read(), kernel_src)
    slots = [0] * KLEN                                   # 0 is NOP
    kused = set()
    for s in ksec:
        if s.kind != "pm" or not KBASE <= s.addr <= s.addr + len(s.words) <= KBASE + KLEN:
            raise SystemExit(f"{kernel_src}: the kernel is code inside {KBASE:#x}..{KBASE + KLEN - 1:#x}")
        slots[s.addr - KBASE: s.addr - KBASE + len(s.words)] = s.words
        kused |= set(range(s.addr, s.addr + len(s.words)))
    klive = range(max(a for a in kused if a - 1 not in kused), KBASE + KLEN)   # last block: the loader itself
    image = pack48(slots)

    psec, syms = sasm.assemble(read_all(prog_srcs), prog_src)
    if entry not in syms:
        raise SystemExit(f"{prog_src}: no entry label '{entry}'")
    recs = []
    for s in psec:
        words, addr = list(s.words), s.addr
        if not words:
            continue
        if s.kind == "pm":
            if any(a in klive for a in range(addr, addr + len(words))):
                raise SystemExit(f"{prog_src}: section at {addr:#x} overwrites the running kernel")
            if addr & 1:
                raise SystemExit(f"{prog_src}: code section at {addr:#x} must start on an even address")
            if len(words) & 1:
                words.append(0)
            words, addr = pack48(words), nw32(addr)
        recs.append((addr, words))
    for addr, words in recs + list(data):
        for i in range(0, len(words), MAXREC):
            image += [addr + i, len(words[i:i + MAXREC])] + list(words[i:i + MAXREC])
    image += [syms[entry], 0]
    return image


def write_header(path, name, image, source, extra=""):
    with open(path, "w") as f:
        f.write(f"/* Generated by tools/sharc/mkboot.py from {source}. */\n{extra}")
        f.write(f"static const uint32_t {name}[{len(image)}] = {{\n")
        for i in range(0, len(image), 6):
            f.write("  " + " ".join(f"0x{w:08x}," for w in image[i:i + 6]) + "\n")
        f.write("};\n")


def main():
    a = sys.argv[1:]
    out = hdr = None
    entry = "START"
    for flag, n in (("-o", 1), ("-c", 2), ("-e", 1)):
        if flag in a:
            i = a.index(flag)
            v = a[i + 1:i + 1 + n]
            del a[i:i + 1 + n]
            if flag == "-o":
                out = v[0]
            elif flag == "-c":
                hdr = v
            else:
                entry = v[0].upper()
    if len(a) < 2:
        sys.exit(__doc__)
    try:
        image = build(a[0], a[1:], entry)
    except sasm.AsmError as e:
        sys.exit(str(e))
    if out:
        open(out, "wb").write(struct.pack("<%dI" % len(image), *image))
    if hdr:
        write_header(hdr[0], hdr[1], image, " and ".join(a))
    print(f"{len(image)} words ({len(image) * 4} bytes), entry {entry}")


if __name__ == "__main__":
    main()
