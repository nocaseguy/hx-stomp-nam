#!/usr/bin/env python3
"""nam2c.py - turn a NAM A2 model (.nam) into a C weight table for src/dsp/nam_a2.c.

A2 .nam files are either a plain WaveNet or a SlimmableContainer holding the
A2-Lite (3 channel) and A2-Full (8 channel) submodels. Pick one with --channels.

Usage: nam2c.py <model.nam> <out.h> [--channels 3|8] [--name nam_model]
"""
import json, sys

def main(a):
    if len(a) < 3: sys.exit(__doc__)
    path, out = a[1], a[2]
    want = int(a[a.index('--channels') + 1]) if '--channels' in a else 3
    name = a[a.index('--name') + 1] if '--name' in a else 'nam_model'
    d = json.load(open(path))
    subs = [s['model'] for s in d['config']['submodels']] if d.get('architecture') == 'SlimmableContainer' else [d]
    for m in subs:
        if m.get('architecture') == 'WaveNet' and m['config']['layers'][0]['channels'] == want:
            break
    else:
        sys.exit(f"no {want}-channel WaveNet in {path}")
    la = m['config']['layers']
    if len(la) != 1 or len(la[0]['kernel_sizes']) != 23 or la[0]['head']['kernel_size'] != 16:
        sys.exit("not an A2-shaped model")
    w = m['weights']
    with open(out, 'w') as f:
        f.write(f"/* Generated by tools/nam2c.py - A2 model, {want} channels, {len(w)} weights. */\n")
        f.write(f"#ifndef {name.upper()}_H\n#define {name.upper()}_H\n")
        f.write(f"#define {name.upper()}_CHANNELS {want}\n#define {name.upper()}_COUNT {len(w)}\n")
        f.write(f"#define {name.upper()}_SAMPLE_RATE {int(m.get('sample_rate', 48000))}\n")
        f.write(f"static const float {name}_weights[{len(w)}] = {{\n")
        for i in range(0, len(w), 6):
            f.write("  " + ", ".join(f"{v:.9g}f" for v in w[i:i + 6]) + ",\n")
        f.write("};\n#endif\n")
    print(f"[+] {out}: {want} channels, {len(w)} weights ({len(w) * 4} bytes)")

if __name__ == '__main__':
    main(sys.argv)
